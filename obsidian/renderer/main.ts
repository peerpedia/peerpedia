import { stdin, stdout } from "node:process";
import { createInterface } from "node:readline";

import { defineDialect, type SyntaxNodeRef } from "bananamark";

import type { PublicationDocument } from "../src/project/document";
import { failure, isRecord, type RenderFailure, type RenderPage, type RenderRequest, type RenderResponse, type SourceTarget } from "./protocol";
import { dialectOptions } from "./site/dialect.js";
import { renderDocument, type SiteHeading, type SiteTarget } from "./site/render-document.mjs";

const MAX_MARKDOWN_BYTES = 1024 * 1024;
const MAX_CHAPTERS = 64;
const parser = defineDialect(dialectOptions).language.language.parser;
const STATIC_URL = "./";
const SITE_TIKZ_FONTS = "./vendor/bananamark/tikz/";

interface Chapter {
  id: string;
  markdown: string;
  title?: string;
}

interface Range {
  from: number;
  to: number;
}

function parseChapters(document: PublicationDocument): readonly Chapter[] {
  if (!isRecord(document) || typeof document.markdown !== "string" ||
      typeof document.bibliography !== "string" || !Array.isArray(document.chapters)) {
    throw new Error("Expected a document with Markdown, chapters and bibliography.");
  }
  if (document.chapters.length > MAX_CHAPTERS) throw new Error("Use up to 64 chapters.");
  const ids = new Set<string>();
  const markup: string[] = [];
  const chapters: readonly Chapter[] = document.chapters.length
    ? document.chapters
    : [{ id: "main", markdown: document.markdown }];
  for (const chapter of chapters) {
    if (!isRecord(chapter) || typeof chapter.id !== "string" ||
      !/^[A-Za-z0-9_-]{1,64}$/.test(chapter.id) || ids.has(chapter.id.toLowerCase())) {
      throw new Error("Chapter IDs must be unique letters, numbers, hyphens or underscores.");
    }
    if (typeof chapter.markdown !== "string") throw new Error("Chapter Markdown must be text.");
    ids.add(chapter.id.toLowerCase());
    markup.push(chapter.markdown);
  }
  const combined = markup.join("\n\n");
  if (document.markdown !== combined) throw new Error("Combined Markdown must exactly match the chapter files.");
  const text = combined + document.bibliography;
  if (/[\u0000\uD800-\uDFFF]/u.test(text) || Buffer.byteLength(text) > MAX_MARKDOWN_BYTES) {
    throw new Error("The complete paper and bibliography must be valid UTF-8, at most 1 MiB, without NUL characters.");
  }
  // A blank draft can be previewed before it meets the website's submission requirements.
  return chapters;
}

function lineRanges(source: string): Range[] {
  const ranges: Range[] = [];
  let from = 0;
  for (const newline of source.matchAll(/\r?\n/g)) {
    ranges.push({ from, to: newline.index });
    from = newline.index + newline[0].length;
  }
  ranges.push({ from, to: source.length });
  return ranges;
}

function fromSiteKind(kind: string): SourceTarget["kind"] | undefined {
  switch (kind) {
    case "page":
    case "heading":
      return "heading";
    case "environment":
      return "theorem";
    case "equation":
      return "equation";
    case "citation":
      return "bibliography";
    default:
      return undefined;
  }
}

function implicitHeadings(
  chapter: Chapter,
  headings: readonly SiteHeading[],
  explicit: ReadonlyMap<string, SourceTarget>,
  sharedBibliography: boolean,
): SourceTarget[] {
  const sourceHeadings: (Range & { level: number })[] = [];
  parser.parse(chapter.markdown).iterate({
    enter(node: SyntaxNodeRef): void {
      const match = /^(?:ATX|Setext)Heading([1-6])$/.exec(node.name);
      if (match) {
        const to = node.to - Number(chapter.markdown[node.to - 1] === "\r");
        sourceHeadings.push({ from: node.from, to, level: Number(match[1]) });
      }
    },
  });
  // The final heading of a bibliography-bearing page is generated by the website.
  const authored = (sharedBibliography ? headings.slice(0, -1) : headings).filter(
    (heading: SiteHeading): boolean => Boolean(heading.id),
  );
  if (authored.length !== sourceHeadings.length) return [];
  const targets: SourceTarget[] = [];
  for (const [index, heading] of authored.entries()) {
    const { from, to, level } = sourceHeadings[index];
    const labelled = explicit.get(heading.id);
    // Skip implicit mappings if the editor grammar and the rendered headings disagree.
    if (heading.level !== level || (labelled && (labelled.from < from || labelled.from >= to))) return [];
    if (!labelled) targets.push({ id: heading.id, chapterId: chapter.id, from, to, kind: "heading", source: "chapter" });
  }
  return targets;
}

function sourceTargets(
  chapter: Chapter,
  headings: readonly SiteHeading[],
  targets: readonly SiteTarget[],
  bibliography: string,
): SourceTarget[] {
  const chapterLines = lineRanges(chapter.markdown);
  const bibLines = lineRanges(bibliography);
  // The website appends two newlines, a References heading, a blank line and the opening YAML fence.
  const bibStart = chapterLines.length + 5;
  const explicit = new Map<string, SourceTarget>();
  for (const target of targets) {
    if (target.chapter !== chapter.id || !target.line || !target.id) continue;
    const kind = fromSiteKind(target.kind);
    if (!kind) continue;
    const shared = kind === "bibliography" && Boolean(bibliography.trim()) && target.line >= bibStart;
    const range = shared ? bibLines[target.line - bibStart] : chapterLines[target.line - 1];
    if (!range) continue;
    explicit.set(target.id, {
      id: target.id, chapterId: chapter.id, ...range, kind, source: shared ? "bibliography" : "chapter",
    });
  }
  return [...explicit.values(), ...implicitHeadings(chapter, headings, explicit, Boolean(bibliography.trim()))];
}

function localFonts(html: string): string {
  // TikZ's generated font sheet precedes the article HTML. Its font files ship in the shared theme.
  return html.replace(/^<style data-tikz-fonts>[^<]*<\/style>/, (style: string): string =>
    style.replaceAll(SITE_TIKZ_FONTS, "./tikz/"),
  );
}

function normalizeError(request: RenderRequest, error: unknown, last?: Chapter): RenderFailure {
  const result = failure(request, error instanceof Error ? error.message : String(error));
  if (!isRecord(error)) return result;
  if (typeof error.file === "string") result.error.file = error.file;
  if (typeof error.line === "number" && error.line > 0) result.error.line = error.line;
  if (typeof error.column === "number" && error.column > 0) result.error.column = error.column;
  if (last && request.document.bibliography.trim() && result.error.file === `${last.id}.md` && result.error.line) {
    const firstBibLine = lineRanges(last.markdown).length + 5;
    if (result.error.line >= firstBibLine) {
      result.error.file = "references.yaml";
      result.error.line -= firstBibLine - 1;
    }
  }
  return result;
}

async function render(request: RenderRequest): Promise<RenderResponse> {
  let last: Chapter | undefined;
  try {
    const chapters = parseChapters(request.document);
    last = chapters.at(-1);
    const output = await renderDocument({
      pages: chapters, bibliography: request.document.bibliography,
      numberSections: request.document.chapters.length > 0, diagrams: true, staticUrl: STATIC_URL,
    });
    return {
      id: request.id,
      revision: request.revision,
      pages: output.pages.map((page: Awaited<ReturnType<typeof renderDocument>>["pages"][number], index: number): RenderPage => ({
        id: page.id,
        title: page.title,
        html: localFonts(page.html),
        targets: sourceTargets(chapters[index], page.headings, output.targets,
          chapters[index] === last ? request.document.bibliography : ""),
      })),
    };
  } catch (error: unknown) {
    return normalizeError(request, error, last);
  }
}

async function respond(line: string): Promise<RenderResponse> {
  let value: unknown;
  try {
    value = JSON.parse(line);
  } catch {
    return failure({ id: "", revision: "" }, "Invalid render request JSON.");
  }
  if (!isRecord(value) || typeof value.id !== "string" || typeof value.revision !== "string") {
    return failure({ id: "", revision: "" }, "A render request requires an ID and revision.");
  }
  return render(value as unknown as RenderRequest);
}

const lines = createInterface({ input: stdin, crlfDelay: Infinity });
for await (const line of lines) {
  const result = await respond(line);
  await new Promise<void>((resolveWrite: () => void, rejectWrite: (error: Error) => void): void => {
    stdout.write(JSON.stringify(result) + "\n", (error?: Error | null): void => {
      if (error) rejectWrite(error);
      else resolveWrite();
    });
  });
}
